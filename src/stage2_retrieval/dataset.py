"""
PyTorch Dataset for Stage-2 (query, segment) contrastive training.

Training pairs come from two places:

  - `data/annotations/<video_id>_pseudo_queries.json` (weak, generated by
    scripts/generate_pseudo_queries.py):
        {"source": "pseudo", "pairs": [{"query": ..., "start_time": ..., "end_time": ...}]}
  - human gold queries (data/annotations/gold/) for TRAIN-split videos only,
    when `use_gold=True`. Gold queries of val/test videos are never trained on.

For each (query, start_time, end_time) pair, the dataset finds the segment
(from `data/segments/<video_id>_segment_features.npz`, produced by Stage 1 +
`segment_features.py`) with maximum temporal IoU against [start_time,
end_time], and pairs the query with that segment's precomputed
(ocr_emb, transcript_emb, visual_emb).

Query text is encoded once at dataset construction time with the frozen
Sentence-BERT text encoder.
"""

import glob
import os
from typing import List

import numpy as np
import torch
from torch.utils.data import Dataset

from config import PATHS
from src.utils.gold import load_gold
from src.utils.io_utils import load_json
from src.stage2_retrieval.segment_features import load_segment_features


def temporal_iou(a_start, a_end, b_start, b_end) -> float:
    inter = max(0.0, min(a_end, b_end) - max(a_start, b_start))
    union = max(a_end, b_end) - min(a_start, b_start)
    if union <= 0:
        return 0.0
    return inter / union


def pseudo_queries_path(video_id: str, annotations_dir: str = PATHS.annotations_dir) -> str:
    return os.path.join(annotations_dir, f"{video_id}_pseudo_queries.json")


class RetrievalPairDataset(Dataset):
    """(query, segment) pairs. Each sample carries `seg_key`, a global id of
    its target segment, so the loss can avoid treating two queries for the
    same segment as each other's negatives."""

    def __init__(self, video_ids: List[str], text_encoder,
                 annotations_dir: str = PATHS.annotations_dir,
                 segments_dir: str = PATHS.segments_dir,
                 use_pseudo: bool = True, use_gold: bool = False):
        self.samples = []
        self.counts = {"pseudo": 0, "gold": 0}
        seg_keys = {}

        for video_id in video_ids:
            pairs = []
            if use_pseudo and os.path.exists(pseudo_queries_path(video_id, annotations_dir)):
                pairs += [(p, "pseudo") for p in load_json(pseudo_queries_path(video_id, annotations_dir))["pairs"]]
            gold = load_gold(video_id) if use_gold else None
            if gold is not None:
                pairs += [(q, "gold") for q in gold["queries"]]
            if not pairs:
                continue

            seg_path = os.path.join(segments_dir, f"{video_id}_segment_features.npz")
            if not os.path.exists(seg_path):
                continue
            seg_feats = load_segment_features(video_id, segments_dir)
            starts, ends = seg_feats["start_times"], seg_feats["end_times"]
            if len(starts) == 0:
                continue

            query_embs = text_encoder.encode([p["query"] for p, _ in pairs])
            for (pair, source), q_emb in zip(pairs, query_embs):
                ious = [temporal_iou(pair["start_time"], pair["end_time"], s, e)
                        for s, e in zip(starts, ends)]
                best_idx = int(np.argmax(ious))
                if ious[best_idx] <= 0:
                    continue
                key = seg_keys.setdefault((video_id, best_idx), len(seg_keys))
                self.samples.append({
                    "ocr_emb": seg_feats["ocr_emb"][best_idx],
                    "transcript_emb": seg_feats["transcript_emb"][best_idx],
                    "visual_emb": seg_feats["visual_emb"][best_idx],
                    "query_emb": q_emb,
                    "seg_key": key,
                })
                self.counts[source] += 1

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        s = self.samples[idx]
        return {
            "ocr_emb": torch.from_numpy(s["ocr_emb"].astype(np.float32)),
            "transcript_emb": torch.from_numpy(s["transcript_emb"].astype(np.float32)),
            "visual_emb": torch.from_numpy(s["visual_emb"].astype(np.float32)),
            "query_emb": torch.from_numpy(s["query_emb"].astype(np.float32)),
            "seg_key": torch.tensor(s["seg_key"], dtype=torch.long),
        }


def list_annotated_video_ids(annotations_dir: str = PATHS.annotations_dir) -> List[str]:
    paths = sorted(glob.glob(os.path.join(annotations_dir, "*_pseudo_queries.json")))
    return [os.path.basename(p).replace("_pseudo_queries.json", "") for p in paths]
